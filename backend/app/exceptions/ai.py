class BaseAiError(Exception):
    """
    Технічна невдача звернення до ШІ.

    Саме технічна: «це не англійське слово» помилкою не є — це нормальна
    змістовна відповідь моделі, вона приїжджає в `AiResultSchema.refusal` і
    слово палить. Сюди потрапляє лише те, у чому людина не винна: мережа,
    таймаут, 5xx, ліміт, відповідь, що не лягла в схему. Такі звернення
    записуються в журнал (вхідні токени вже оплачені), але слова не палять.

    `code` іде в `ai_requests.error_code` — щоб на питання «чому рахунок
    більший, ніж успішних заповнень» була відповідь без читання логів.
    """

    code = "ai_error"

    def __init__(self, message: str = "", code: str | None = None) -> None:
        # Уточнений код дозволяє розрізнити в журналі те, що для роута
        # однакове: таймаут, 502 і «модель відмовилась з міркувань безпеки»
        # усі дають 502 назовні, але дивитись на них треба по-різному.
        if code:
            self.code = code
        super().__init__(message or self.code)


class AiUnavailableError(BaseAiError):
    """Claude не відповів: мережа, таймаут, 5xx, перевантаження."""

    code = "ai_unavailable"


class AiRateLimitedError(BaseAiError):
    """Уперлися в ліміт Anthropic. Відрізняється від решти тим, що мине саме."""

    code = "ai_rate_limited"


class AiInvalidResponseError(BaseAiError):
    """
    Відповідь не лягла в схему.

    Зі структурованим виводом це рідкість, але не неможливість: моделі
    дозволено зупинитись на межі токенів або відмовитись з міркувань безпеки, і
    тоді розбирати немає чого.
    """

    code = "ai_invalid_response"
