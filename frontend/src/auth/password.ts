/**
 * Правила пароля — дзеркало `validate_password_strength` на бекенді.
 *
 * Дзеркалимо, щоб не питати сервер п'ять разів поспіль: без цього людина
 * дізнається про вимоги по одній, кожна ціною запиту й повного перезаповнення
 * форми. Порядок перевірок той самий, що на сервері, — інакше перша скарга
 * локально й перша скарга з сервера різнились би.
 *
 * УВАГА: `[A-Z]` і `[a-z]` — саме латиниця, як на бекенді. «Пароль123!» із
 * українськими літерами вимогу НЕ задовольняє, і мовчки «виправляти» це тут
 * не можна: тоді локальна перевірка казала б «добре», а сервер відповідав би
 * «ні», і винним виглядав би застосунок.
 */

const SPECIAL = /[@$!%*?&#]/;

/** Що саме не так із паролем. `null` — усе гаразд. */
export function passwordProblem(password: string): string | null {
  if (password.length < 8) return "Пароль має містити щонайменше 8 символів.";
  if (!/[A-Z]/.test(password)) {
    return "Пароль має містити щонайменше одну велику латинську літеру.";
  }
  if (!/[a-z]/.test(password)) {
    return "Пароль має містити щонайменше одну малу латинську літеру.";
  }
  if (!/\d/.test(password)) return "Пароль має містити щонайменше одну цифру.";
  if (!SPECIAL.test(password)) {
    return "Пароль має містити щонайменше один спеціальний символ: @ $ ! % * ? # &";
  }
  return null;
}

/**
 * Підпис під полем.
 *
 * Стоїть там завжди, а не з'являється помилкою: вимоги треба знати ДО набору, а
 * не після відмови. «Латинські» сказано явно — це єдине, на чому спотикається
 * українськомовний користувач.
 */
export const PASSWORD_HINT =
  "Щонайменше 8 символів: велика й мала латинські літери, цифра і один зі знаків @ $ ! % * ? # &";

/** Пошта, яку варто слати на сервер: без пробілів по краях. */
export function normalizeEmail(email: string): string {
  return email.trim();
}

/**
 * Чи схоже це на пошту взагалі.
 *
 * Навмисно груба перевірка: сувору робить бекенд через `email_validator`, і
 * дублювати її регуляркою означало б відхиляти адреси, які сервер приймає.
 * Тут потрібно рівно одне — не слати запит на порожньому чи очевидно
 * незакінченому вводі.
 */
export function emailLooksWrong(email: string): boolean {
  const value = normalizeEmail(email);
  if (!value) return true;
  const at = value.indexOf("@");
  if (at <= 0) return true;
  const domain = value.slice(at + 1);
  return !domain.includes(".") || domain.startsWith(".") || domain.endsWith(".");
}
