/**
 * Смужка обсягу за період.
 *
 * Відповідає на те, чого не каже жодне число в панелі: рівномірно ти вчишся чи
 * ривками. «84 повторення за тиждень» однакові в того, хто робив по 12 щодня, і
 * в того, хто зробив усе в суботу.
 *
 * Стовпчики НЕ фарбуються рампою сяйва. Висота тут означає обсяг, а насичений
 * колір у цьому застосунку означає стан памʼяті слова (ADR-0012) — пофарбувати
 * ним обсяг було б брехнею того ж роду, що зелена кнопка «Добре». Тому смужка
 * лишається в хромі, а золото на цьому екрані належить календарю, де воно
 * означає рівно одне: день закрито.
 *
 * Порожній відрізок малюється обрубком, а не нічим. Прогалина в ряду читається
 * як «тут кінець даних», а обрубок — як «тут нуль», і це різні новини.
 */

import type { VolumeBar } from "../study/period";

export default function Spark({ bars }: { bars: VolumeBar[] }) {
  // Масштаб від найбільшого стовпчика, а не від цілі: у «загалом» місячні суми
  // на два порядки більші за денні, і спільної шкали між періодами бути не може.
  const peak = bars.reduce((top, bar) => Math.max(top, bar.value), 0);

  if (bars.length === 0) return null;

  return (
    <div className="spark" aria-hidden="true">
      <div className="spark-bars">
        {bars.map((bar) => (
          <span className="spark-col" key={bar.key}>
            <i
              className={bar.now ? "spark-b spark-b-now" : "spark-b"}
              style={{
                // Обрубок у 2px лишається навіть у нуля — див. шапку файлу.
                height:
                  peak > 0
                    ? `${Math.max(2, (bar.value / peak) * 100)}%`
                    : "2px",
              }}
            />
          </span>
        ))}
      </div>
      <div className="spark-ticks">
        {bars.map((bar) => (
          <span className="spark-t" key={bar.key}>
            {bar.tick}
          </span>
        ))}
      </div>
    </div>
  );
}
