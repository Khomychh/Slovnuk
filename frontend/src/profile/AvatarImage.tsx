/**
 * Фото профілю — з поверненням до літери, коли картинка не приїхала.
 *
 * Компонент існує через конкретний збій. Адресу аватара будує бекенд із
 * `S3_STORAGE_PUBLIC_ENDPOINT`; якщо на сервері там лишилось значення для
 * розробки (`http://localhost:9000`), браузер ріже її як mixed content на
 * https-сторінці — **мовчки**, без запису в мережі й без помилки в консолі.
 * Голий `<img>` показував у цьому разі порожнє коло, і виглядало це так, ніби
 * завантаження не спрацювало, хоча файл лежав у сховищі.
 *
 * Літера замість дірки не лікує конфігурацію, але перестає брехати: стан
 * «фото нема» і стан «фото є, але його не видно» зливаються в один, і обидва
 * читаються як «фото поки нема» — що для аватара правда достатня.
 */

import { useEffect, useState } from "react";

export function AvatarImage({
  src,
  initial,
  onFail,
}: {
  src: string | null;
  /** Перша літера імені або пошти — те, що стоїть замість фото. */
  initial: string;
  /** Кажуть екранові профілю, щоб той пояснив, чому фото не видно. */
  onFail?: () => void;
}) {
  const [failed, setFailed] = useState(false);

  // Нова адреса — нова спроба. Без цього мітка версії після заміни фото
  // впиралась би в `failed` від попередньої картинки.
  useEffect(() => setFailed(false), [src]);

  if (!src || failed) return <span>{initial}</span>;

  return (
    <img
      src={src}
      alt=""
      onError={() => {
        setFailed(true);
        onFail?.();
      }}
    />
  );
}
